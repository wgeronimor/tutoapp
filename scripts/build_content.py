UNIT_PAGES = {0: 11, 1: 17, 2: 31, 3: 45, 4: 59, 5: 73}


def item(text):
    norm = text.lower().replace("’", "'").strip(" .!?")
    return "fr:expression:" + hashlib.sha256(norm.encode()).hexdigest()[:20]


def build():
    days = []
    for n, (
        title,
        unit,
        goal,
        phrases,
        reading,
        q,
        answer,
        others,
        write,
        speak,
        tip,
    ) in enumerate(DAYS, 1):
        dayof = (n - 1) % 7
        block = "Programa propio"
        acts = []
        source = {
            "book": "Édito A1, 2e édition, 2022",
            "unit": unit,
            "printed_page": UNIT_PAGES[unit],
            "pdf_page": 1,
            "relationship": "Alineación temática; actividades originales",
        }

        def add(suffix, **kw):
            acts.append(
                {
                    "key": f"day-{n}:{suffix}",
                    "origin": "Contenido original revisado",
                    "source": source,
                    **kw,
                }
            )

        if dayof < 4:
            # Keep each exercise schema explicit and small.
            add(
                "preview",
                title="Antes de clase · objetivo y ensayo",
                skill="reading",
                mode="open",
                prompt=f"Lee la explicación. Recupera tres expresiones, formula una pregunta y escribe qué quieres entender en clase. U{unit}; agenda estimada hasta confirmación.",
                material=tip + "\n" + "\n".join(x[0] + " — " + x[1] for x in phrases),
                reference=phrases[0][0],
                item=item(phrases[0][0]),
                block="Antes de clase",
                minutes=25,
                explanation="Comprueba que identificas el objetivo y puedes formular una pregunta. Verifica con una tarea tras la clase.",
            )
            add(
                "review",
                title="Después de clase · recuperación",
                skill="writing",
                mode="open",
                prompt="Sin mirar los apuntes: escribe tres cosas aprendidas, una pregunta que respondiste y una dificultad. Si aún no hubo clase, realiza este bloque después.",
                material="",
                reference=phrases[1][0],
                item=item(phrases[1][0]),
                block="Después de clase",
                minutes=15,
                explanation="Compara tus notas con la clase y prueba una frase nueva. Marca la dificultad en Mis clases.",
            )
        # Five active sentences: context, retrieval, handwriting, variation and reference audio.
        for i, (fr, es) in enumerate(phrases):
            add(
                f"phrase-{i + 1}",
                title=f"Frase activa {i + 1} · de memoria",
                skill="writing",
                mode="exact",
                prompt=f"Escucha y comprende. Después escribe de memoria: «{es}». Puedes usar tu cuaderno y marcarlo; introduce aquí la respuesta para corregirla.",
                reference=fr,
                accepted=[fr],
                explanation="Forma de referencia: " + fr + " " + tip,
                meaning=es,
                variation="Cambia un dato, una persona o el destinatario y úsala en una respuesta espontánea.",
                item=item(fr),
                block=block,
                minutes=6,
            )
        add(
            "listen",
            title="Escuchar · situación nueva",
            skill="listening",
            mode="choice",
            prompt="Escucha primero sin transcripción. " + q,
            reference=reading,
            accepted=[answer],
            options=[others[0], answer, others[1]],
            explanation="El dato está en este mensaje: " + reading,
            item=f"fr:objective:u{unit}:listen",
            block=block,
            minutes=10,
        )
        # A different inference/data point from the same accessible text.
        add(
            "read",
            title="Leer · localizar la evidencia",
            skill="reading",
            mode="choice",
            prompt=q + " Localiza la frase que respalda tu elección.",
            material=reading,
            reference=reading,
            accepted=[answer],
            options=[answer, *others],
            explanation="Vuelve al texto y localiza el dato: " + answer,
            item=f"fr:objective:u{unit}:read",
            block=block,
            minutes=10,
        )
        add(
            "write",
            title="Escribir · aplicar y reescribir",
            skill="writing",
            mode="open",
            prompt=write,
            material=tip,
            reference=phrases[2][0],
            explanation="Rúbrica: cumplir la consigna, transmitir una idea clara, usar vocabulario adecuado y revisar la forma. Conserva el original; reescribe después de la corrección.",
            item=f"fr:objective:u{unit}:write",
            block=block,
            minutes=15,
        )
        add(
            "repeat",
            title="Hablar · escuchar y repetir",
            skill="speaking",
            mode="speak",
            prompt="Escucha la referencia, graba tu versión y compárala. Después cambia un dato y vuelve a grabar.",
            reference=phrases[0][0],
            explanation="La transcripción permite revisar el contenido. La evaluación acústica de pronunciación sigue pendiente de validación.",
            item=item(phrases[0][0]),
            block=block,
            minutes=7,
        )
        add(
            "speak",
            title="Hablar · sin leer",
            skill="speaking",
            mode="speak",
            prompt=speak,
            reference="",
            explanation="Revisa cumplimiento, claridad, interacción y vocabulario. Guarda la muestra y repite con una variante. Los comentarios automáticos son orientativos.",
            item=f"fr:objective:u{unit}:speak",
            block=block,
            minutes=8,
        )
        # Weekends use the extra 40 minutes for correction, transfer and cumulative recovery.
        if dayof >= 4:
            for a in acts:
                a["minutes"] += 4
        assert sum(a["minutes"] for a in acts) == 120
        days.append(
            {
                "day": n,
                "week": (n - 1) // 7 + 1,
                "title": title,
                "goal": goal,
                "unit": unit,
                "tip": tip,
                "evaluation": n in (1, 6, 13, 20, 27),
                "activities": acts,
            }
        )
    (ROOT / "content/course-v1.json").write_text(
        json.dumps({"version": "a1-4weeks-1", "days": days}, ensure_ascii=False, indent=2) + "\n"
    )


if __name__ == "__main__":
    build()
